"""服务侧的薄弱线：什么叫"这个考点还没掌握"，只许有一个出处。

这条线不是库内数据——`数据集/**` 里没有"多少分算薄弱"这种卷面事实，它是本服务自定的复习触发线，
因此必须随结果一起说明它的来历。它同时被三个层用：诊断按考点的作答正确率筛薄弱项、排课按持久化
掌握度决定谁进"薄弱专项"、组卷在按掌握度相对排序时用它解释"相对最低不等于薄弱"。

以前这条线有三份各自的说法：诊断写 0.60、排课写 0.50、排课的专项练习干脆不看线（只要有掌握度记录
就挂"薄弱考点专项"的标题，把 0.90 的考点也叫薄弱）。同一个学习者在同一条闭环（诊断→规划→组卷）里
被两边用两个数判定：诊断报 0.55 的考点是薄弱项，日历却把它归为"已掌握"排到所有未练考点之后。
"""
from __future__ import annotations

#: 低于这条线才算薄弱；等于这条线不算。
WEAK_MASTERY_BAR: float = 0.60


def is_weak(score: float) -> bool:
    return score < WEAK_MASTERY_BAR


def weakness_bar_notice() -> str:
    """把线的来历一次说清：谁在用这条线、量的是哪个数、它不是官方分数线。"""
    return (
        f"薄弱线取 {WEAK_MASTERY_BAR:.2f}（低于该线才算薄弱）：诊断按考点的作答正确率、"
        "排课与复习按持久化掌握度，本服务的这几处共用这一条线。它是本服务自定的复习触发线，"
        "不是库内卷面事实，也不是教研核定的分数线。"
    )
